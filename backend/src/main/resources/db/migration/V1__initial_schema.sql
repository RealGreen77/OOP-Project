-- =====================================================================================
-- I-ITSM initial schema (PostgreSQL; portable to H2 in PostgreSQL mode for tests).
-- Hibernate runs with ddl-auto=validate, so this file is the single source of truth.
-- =====================================================================================

-- ---------------------------------------------------------------- catalog
CREATE TABLE categories (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(40)  NOT NULL UNIQUE,
    name         VARCHAR(80)  NOT NULL,
    description  VARCHAR(500),
    active       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE category_keywords (
    category_id  BIGINT      NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
    keyword      VARCHAR(60) NOT NULL,
    PRIMARY KEY (category_id, keyword)
);

CREATE TABLE it_services (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(40)  NOT NULL UNIQUE,
    name                VARCHAR(100) NOT NULL,
    description         VARCHAR(500),
    criticality         VARCHAR(20)  NOT NULL,
    owner_team          VARCHAR(80),
    default_category_id BIGINT REFERENCES categories (id),
    active              BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE service_dependencies (
    service_id    BIGINT NOT NULL REFERENCES it_services (id) ON DELETE CASCADE,
    depends_on_id BIGINT NOT NULL REFERENCES it_services (id) ON DELETE CASCADE,
    PRIMARY KEY (service_id, depends_on_id)
);

-- ---------------------------------------------------------------- users (single-table inheritance)
CREATE TABLE users (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_type                VARCHAR(20)  NOT NULL,
    user_code                VARCHAR(20)  NOT NULL UNIQUE,
    full_name                VARCHAR(120) NOT NULL,
    email                    VARCHAR(160) NOT NULL UNIQUE,
    password_hash            VARCHAR(100) NOT NULL,
    department               VARCHAR(80),
    phone                    VARCHAR(20),
    active                   BOOLEAN      NOT NULL DEFAULT TRUE,
    failed_login_attempts    INT          NOT NULL DEFAULT 0,
    locked_until             TIMESTAMP WITH TIME ZONE,
    last_login_at            TIMESTAMP WITH TIME ZONE,
    pref_email               BOOLEAN      NOT NULL DEFAULT TRUE,
    pref_sms                 BOOLEAN      NOT NULL DEFAULT FALSE,
    -- technician / team lead columns
    experience_years         INT,
    max_concurrent_incidents INT,
    availability             VARCHAR(20),
    team_lead_id             BIGINT REFERENCES users (id),
    created_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at               TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_users_type ON users (user_type);

CREATE TABLE technician_skills (
    technician_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    category_id   BIGINT NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
    PRIMARY KEY (technician_id, category_id)
);

CREATE TABLE technician_services (
    technician_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    service_id    BIGINT NOT NULL REFERENCES it_services (id) ON DELETE CASCADE,
    PRIMARY KEY (technician_id, service_id)
);

-- ---------------------------------------------------------------- SLA
CREATE TABLE sla_policies (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(100) NOT NULL,
    priority              VARCHAR(4)   NOT NULL,
    response_minutes      INT          NOT NULL CHECK (response_minutes > 0),
    resolution_minutes    INT          NOT NULL CHECK (resolution_minutes > 0),
    warning_threshold_pct INT          NOT NULL DEFAULT 75,
    service_id            BIGINT REFERENCES it_services (id),
    active                BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_sla_lookup ON sla_policies (priority, service_id);

-- ---------------------------------------------------------------- incidents
CREATE TABLE incidents (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_number           VARCHAR(20) UNIQUE,
    title                     VARCHAR(200)  NOT NULL,
    description               VARCHAR(4000) NOT NULL,
    reporter_id               BIGINT        NOT NULL REFERENCES users (id),
    category_id               BIGINT REFERENCES categories (id),
    service_id                BIGINT        NOT NULL REFERENCES it_services (id),
    impact                    VARCHAR(10)   NOT NULL,
    urgency                   VARCHAR(10)   NOT NULL,
    affected_users            INT           NOT NULL DEFAULT 1,
    priority                  VARCHAR(4),
    priority_score            DOUBLE PRECISION,
    priority_rationale        VARCHAR(500),
    status                    VARCHAR(20)   NOT NULL,
    assigned_to_id            BIGINT REFERENCES users (id),
    reported_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    assigned_at               TIMESTAMP WITH TIME ZONE,
    acknowledged_at           TIMESTAMP WITH TIME ZONE,
    resolved_at               TIMESTAMP WITH TIME ZONE,
    verified_at               TIMESTAMP WITH TIME ZONE,
    closed_at                 TIMESTAMP WITH TIME ZONE,
    -- embedded SLA record
    sla_policy_name           VARCHAR(100),
    sla_response_minutes      INT,
    sla_resolution_minutes    INT,
    sla_warning_pct           INT,
    sla_started_at            TIMESTAMP WITH TIME ZONE,
    sla_response_deadline     TIMESTAMP WITH TIME ZONE,
    sla_resolution_deadline   TIMESTAMP WITH TIME ZONE,
    sla_responded_at          TIMESTAMP WITH TIME ZONE,
    sla_response_breached     BOOLEAN DEFAULT FALSE,
    sla_resolution_breached   BOOLEAN DEFAULT FALSE,
    sla_warning_issued        BOOLEAN DEFAULT FALSE,
    sla_paused_at             TIMESTAMP WITH TIME ZONE,
    sla_paused_seconds        BIGINT DEFAULT 0,
    -- embedded resolution
    resolution_summary        VARCHAR(2000),
    resolution_root_cause     VARCHAR(1000),
    resolution_workaround     BOOLEAN DEFAULT FALSE,
    -- closure
    closure_code              VARCHAR(30),
    closure_notes             VARCHAR(1000),
    -- embedded feedback
    feedback_rating           INT CHECK (feedback_rating IS NULL OR feedback_rating BETWEEN 1 AND 5),
    feedback_comment          VARCHAR(1000),
    feedback_at               TIMESTAMP WITH TIME ZONE,
    -- escalation & intelligence
    escalation_level          INT    NOT NULL DEFAULT 0,
    last_escalated_at         TIMESTAMP WITH TIME ZONE,
    reopen_count              INT    NOT NULL DEFAULT 0,
    duplicate_of_id           BIGINT REFERENCES incidents (id),
    suspected_duplicate_of_id BIGINT REFERENCES incidents (id),
    suspected_duplicate_score DOUBLE PRECISION,
    version                   BIGINT NOT NULL DEFAULT 0,
    created_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at                TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_incidents_status      ON incidents (status);
CREATE INDEX idx_incidents_priority    ON incidents (priority);
CREATE INDEX idx_incidents_service     ON incidents (service_id);
CREATE INDEX idx_incidents_category    ON incidents (category_id);
CREATE INDEX idx_incidents_assignee    ON incidents (assigned_to_id);
CREATE INDEX idx_incidents_reporter    ON incidents (reporter_id);
CREATE INDEX idx_incidents_reported_at ON incidents (reported_at);

CREATE TABLE incident_notes (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id   BIGINT        NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    author_id     BIGINT REFERENCES users (id),
    note_type     VARCHAR(20)   NOT NULL,
    content       VARCHAR(4000) NOT NULL,
    internal_only BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_notes_incident ON incident_notes (incident_id);

-- ---------------------------------------------------------------- audit (append-only)
CREATE TABLE audit_entries (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    actor_id       BIGINT,
    actor_name     VARCHAR(150)  NOT NULL,
    actor_role     VARCHAR(20),
    action         VARCHAR(40)   NOT NULL,
    entity_type    VARCHAR(30)   NOT NULL,
    entity_id      BIGINT,
    entity_ref     VARCHAR(40),
    previous_state VARCHAR(60),
    new_state      VARCHAR(60),
    description    VARCHAR(1000) NOT NULL
);
CREATE INDEX idx_audit_entity   ON audit_entries (entity_type, entity_id);
CREATE INDEX idx_audit_occurred ON audit_entries (occurred_at);
CREATE INDEX idx_audit_actor    ON audit_entries (actor_id);

-- ---------------------------------------------------------------- notifications
CREATE TABLE notifications (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id    BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    channel         VARCHAR(10)   NOT NULL,
    event_type      VARCHAR(40)   NOT NULL,
    title           VARCHAR(200)  NOT NULL,
    message         VARCHAR(2000) NOT NULL,
    incident_id     BIGINT,
    incident_number VARCHAR(20),
    destination     VARCHAR(160),
    delivery_status VARCHAR(12)   NOT NULL,
    failure_reason  VARCHAR(500),
    is_read         BOOLEAN       NOT NULL DEFAULT FALSE,
    read_at         TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_notifications_inbox ON notifications (recipient_id, channel, is_read);

-- ---------------------------------------------------------------- runtime configuration
CREATE TABLE system_settings (
    setting_key   VARCHAR(80)  PRIMARY KEY,
    setting_value VARCHAR(500) NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by    VARCHAR(150)
);
