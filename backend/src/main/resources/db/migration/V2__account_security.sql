-- Account security: e-mail verification for self-registration and self-service password reset.

-- One-time 6-digit registration codes. Only the BCrypt hash of the code is stored; one pending code per address.
CREATE TABLE email_verifications (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email        VARCHAR(160) NOT NULL UNIQUE,
    code_hash    VARCHAR(100) NOT NULL,
    expires_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    attempts     INT          NOT NULL DEFAULT 0,
    last_sent_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Password-reset links. The token is sent by e-mail; only its SHA-256 hash is stored. Single use.
CREATE TABLE password_reset_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id),
    token_hash VARCHAR(64)  NOT NULL UNIQUE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at    TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_password_reset_user ON password_reset_tokens (user_id);
